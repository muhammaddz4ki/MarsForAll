for (const [lang, data] of Object.entries(dicts)) {
  const langPaths = extractAllPaths(data);
  const missing = enPaths.filter((p) => !langPaths.includes(p));
  const extra = langPaths.filter((p) => !enPaths.includes(p));

  if (missing.length > 0 || extra.length > 0) {
    console.error(`[i18n-sync] Mismatch in '${lang}': missing ${missing.length}, extra ${extra.length}`);
    if (missing.length) console.error("  Missing keys:", missing);
    if (extra.length) console.error("  Extra keys:", extra);
    process.exit(1);
  }

  const filePath = path.join(MESSAGES_DIR, `${lang}.json`);
  fs.writeFileSync(filePath, JSON.stringify(data, null, 2) + "\n", "utf8");
  console.log(`[i18n-sync] Wrote ${lang}.json (${langPaths.length} keys) -> 100% matched.`);
}

